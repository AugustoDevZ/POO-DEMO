    private void btnCalcularCirculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularCirculoActionPerformed
        try {
            if (txtRadio.getText().trim().isEmpty()) {
                throw new IllegalArgumentException("El campo del radio no puede estar vacío.");
            }

            double radio = Double.parseDouble(txtRadio.getText().trim());

            if (radio <= 0) {
                throw new ArithmeticException("El radio debe ser mayor a 0.");
            }

            String unidadIngreso = jComboBox1.getSelectedItem().toString();
            Circulo circulo = new Circulo(radio, unidadIngreso);

            double areaFinal;
            String unidadFinal;
            String pasoAPaso;

            if (tglConvertir.isSelected()) {
                String unidadDestino = jComboBoxDestino.getSelectedItem().toString();
                areaFinal = circulo.convertirAreaA(unidadDestino);
                unidadFinal = unidadDestino;

                double radioConvertido = radio * obtenerFactorPrueba(unidadIngreso) / obtenerFactorPrueba(unidadDestino);
                pasoAPaso = String.format("Conv. (%.1f %s a %s) -> π × (%.2f)² = %.4f",
                        radio, unidadIngreso, unidadDestino, radioConvertido, areaFinal);
            } else {
                areaFinal = circulo.calcularArea();
                unidadFinal = unidadIngreso;
                pasoAPaso = String.format("π × (%.2f)² = %.4f", radio, areaFinal);
            }

            lblResultadoCirculo.setText(String.format("Área: %.4f %s²", areaFinal, unidadFinal));

            // Añade al historial de la tabla una sola vez
            modeloTablaCirculo.addRow(new Object[]{radio, unidadIngreso, String.format("%.4f %s²", areaFinal, unidadFinal), pasoAPaso});

            canvasCirculo.setRadio(radio);
            String unidadDestinoStr = tglConvertir.isSelected() ? jComboBoxDestino.getSelectedItem().toString() : "";
            canvasCirculo.setResultadoInfo(areaFinal, unidadFinal, tglConvertir.isSelected(), unidadIngreso, unidadDestinoStr);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: Ingrese solo un valor numérico válido.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error de Validación", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCalcularCirculoActionPerformed

