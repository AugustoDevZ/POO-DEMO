    /**
     * Método auxiliar para calcular y mostrar en tiempo real en la interfaz sin saturar la tabla
     */
    private void actualizarCalculoEnVivo(double radio) {
        try {
            String unidadIngreso = jComboBox1.getSelectedItem().toString();
            Circulo circulo = new Circulo(radio, unidadIngreso);
            double areaFinal;
            String unidadFinal;

            if (tglConvertir.isSelected()) {
                String unidadDestino = jComboBoxDestino.getSelectedItem().toString();
                areaFinal = circulo.convertirAreaA(unidadDestino);
                unidadFinal = unidadDestino;
            } else {
                areaFinal = circulo.calcularArea();
                unidadFinal = unidadIngreso;
            }

            lblResultadoCirculo.setText(String.format("Área: %.4f %s²", areaFinal, unidadFinal));

            canvasCirculo.setRadio(radio);
            String unidadDestinoStr = tglConvertir.isSelected() ? jComboBoxDestino.getSelectedItem().toString() : "";
            canvasCirculo.setResultadoInfo(areaFinal, unidadFinal, tglConvertir.isSelected(), unidadIngreso, unidadDestinoStr);
        } catch (Exception e) {
            // Ignorar errores menores durante el movimiento fluido del mouse
        }
    }

