    private void btnCalcularRectanguloActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularRectanguloActionPerformed
try {
            if (txtBase.getText().trim().isEmpty() || txtAltura.getText().trim().isEmpty()) {
                throw new IllegalArgumentException("Los campos de base y altura no pueden estar vacíos.");
            }
            
            double base = Double.parseDouble(txtBase.getText().trim());
            double altura = Double.parseDouble(txtAltura.getText().trim());
            
            if (base <= 0 || altura <= 0) {
                throw new ArithmeticException("La base y la altura deben ser mayores a 0.");
            }
            
            String unidadIngreso = jComboBox1.getSelectedItem().toString();
            Rectangulo rectangulo = new Rectangulo(base, altura, unidadIngreso);
            
            double areaFinal;
            String unidadFinal;
            String pasoAPaso;
            
            if (tglConvertir.isSelected()) {
                String unidadDestino = jComboBoxDestino.getSelectedItem().toString();
                areaFinal = rectangulo.convertirAreaA(unidadDestino);
                unidadFinal = unidadDestino;
                
                double factor = obtenerFactorPrueba(unidadIngreso) / obtenerFactorPrueba(unidadDestino);
                double baseConv = base * factor;
                double alturaConv = altura * factor;
                pasoAPaso = String.format("Conv. (%.1f y %.1f %s a %s) -> %.2f × %.2f = %.4f", 
                        base, altura, unidadIngreso, unidadDestino, baseConv, alturaConv, areaFinal);
            } else {
                areaFinal = rectangulo.calcularArea();
                unidadFinal = unidadIngreso;
                pasoAPaso = String.format("%.2f × %.2f = %.4f", base, altura, areaFinal);
            }
            
            lblResultadoRectangulo.setText(String.format("Área: %.4f %s²", areaFinal, unidadFinal));
            
            // Añade al historial de la tabla una sola vez
            modeloTablaRectangulo.addRow(new Object[]{base, altura, unidadIngreso, String.format("%.4f %s²", areaFinal, unidadFinal), pasoAPaso});
            
            canvasRectangulo.setDimensiones(base, altura);
            String unidadDestinoStr = tglConvertir.isSelected() ? jComboBoxDestino.getSelectedItem().toString() : "";
            canvasRectangulo.setResultadoInfo(areaFinal, unidadFinal, tglConvertir.isSelected(), unidadIngreso, unidadDestinoStr);
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: Ingrese solo valores numéricos válidos.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error de Validación", JOptionPane.ERROR_MESSAGE);
        }
    }
