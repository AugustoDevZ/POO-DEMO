// Método auxiliar rápido para calcular los lados convertidos en el texto del paso a paso
private double obtenerFactorPrueba(String unidad) {
if (unidad.contains("Milímetros")) return 0.001;
        if (unidad.contains("Centímetros")) return 0.01;
        if (unidad.contains("Decímetros")) return 0.1;
        if (unidad.contains("Metros")) return 1.0;
        if (unidad.contains("Kilómetros")) return 1000.0;
        return 1.0;
    }//GEN-LAST:event_btnCalcularRectanguloActionPerformed

